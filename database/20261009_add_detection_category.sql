BEGIN;

CREATE TABLE IF NOT EXISTS detection_category (
    detection_category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    major_category_name varchar(200) NOT NULL,
    detection_category_name varchar(200) NOT NULL,
    unit_id integer NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    sort_order integer NOT NULL DEFAULT 0,
    CONSTRAINT fk_detection_category_unit
        FOREIGN KEY (unit_id)
        REFERENCES unit_master(unit_id)
        ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_detection_category_name
    ON detection_category (
        major_category_name,
        detection_category_name
    );

CREATE TABLE IF NOT EXISTS detection_category_material_map (
    material_id integer PRIMARY KEY,
    detection_category_id integer NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT fk_detection_map_category
        FOREIGN KEY (detection_category_id)
        REFERENCES detection_category(detection_category_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_detection_map_material
        FOREIGN KEY (material_id)
        REFERENCES material_master(material_id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_detection_map_category
    ON detection_category_material_map (
        detection_category_id
    );

COMMIT;
