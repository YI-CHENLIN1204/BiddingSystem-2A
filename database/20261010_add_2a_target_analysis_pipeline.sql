CREATE TABLE IF NOT EXISTS analysis_case (
    analysis_case_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_name varchar(250) NOT NULL,
    project_type varchar(100) NOT NULL,
    structure_type varchar(100) NOT NULL,
    city varchar(100) NOT NULL,
    total_floor_area numeric(20,4) NOT NULL,
    floor_count integer NOT NULL,
    basement_floor_count integer NOT NULL DEFAULT 0,
    project_date date NOT NULL,
    status varchar(30) NOT NULL DEFAULT 'Active',
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT ck_analysis_case_floor_area CHECK (total_floor_area > 0),
    CONSTRAINT ck_analysis_case_floor_count CHECK (floor_count > 0),
    CONSTRAINT ck_analysis_case_basement CHECK (basement_floor_count >= 0)
);

CREATE TABLE IF NOT EXISTS analysis_bid_version (
    analysis_bid_version_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_case_id integer NOT NULL,
    version_no integer NOT NULL,
    source_type varchar(20) NOT NULL,
    source_1d_project_id integer NULL,
    source_file_name varchar(500) NULL,
    source_file_hash varchar(128) NULL,
    source_note text NULL,
    is_current boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT fk_analysis_version_case
        FOREIGN KEY (analysis_case_id)
        REFERENCES analysis_case(analysis_case_id)
        ON DELETE CASCADE,
    CONSTRAINT ux_analysis_case_version_no
        UNIQUE (analysis_case_id, version_no),
    CONSTRAINT ck_analysis_version_no
        CHECK (version_no > 0),
    CONSTRAINT ck_analysis_version_source
        CHECK (source_type IN ('OneD', 'Upload'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_analysis_bid_version_current
    ON analysis_bid_version(analysis_case_id)
    WHERE is_current = true;

CREATE INDEX IF NOT EXISTS ix_analysis_bid_version_case
    ON analysis_bid_version(analysis_case_id);

CREATE INDEX IF NOT EXISTS ix_analysis_bid_version_1d_source
    ON analysis_bid_version(source_1d_project_id)
    WHERE source_1d_project_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS analysis_bid_item (
    analysis_bid_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_bid_version_id bigint NOT NULL,
    source_sequence integer NULL,
    sheet_name varchar(250) NULL,
    row_number integer NULL,
    item_code varchar(250) NULL,
    source_category1 varchar(250) NULL,
    source_category2 varchar(250) NULL,
    source_category3 varchar(250) NULL,
    major_category varchar(250) NULL,
    item_name text NOT NULL,
    spec text NULL,
    unit varchar(100) NULL,
    quantity numeric(20,6) NULL,
    unit_price numeric(20,6) NULL,
    amount numeric(20,2) NULL,
    source_confidence numeric(10,6) NULL,
    note text NULL,
    CONSTRAINT fk_analysis_item_version
        FOREIGN KEY (analysis_bid_version_id)
        REFERENCES analysis_bid_version(analysis_bid_version_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_analysis_bid_item_version
    ON analysis_bid_item(analysis_bid_version_id);

CREATE INDEX IF NOT EXISTS ix_analysis_bid_item_major_category
    ON analysis_bid_item(analysis_bid_version_id, major_category);

CREATE TABLE IF NOT EXISTS analysis_run (
    analysis_run_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_bid_version_id bigint NOT NULL,
    run_type varchar(120) NOT NULL,
    status varchar(30) NOT NULL,
    result_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT fk_analysis_run_version
        FOREIGN KEY (analysis_bid_version_id)
        REFERENCES analysis_bid_version(analysis_bid_version_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_analysis_run_version_created
    ON analysis_run(analysis_bid_version_id, created_at DESC);

CREATE INDEX IF NOT EXISTS ix_analysis_case_updated_at
    ON analysis_case(updated_at DESC);